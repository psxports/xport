import tempfile
import unittest
from pathlib import Path

import startup


class RefreshPsyqTests(unittest.TestCase):
    def fixture(self, root, status='complete', detector='xport'):
        (root / 'status').mkdir()
        startup.atomic_json(root / 'xport-project.json', {
            'paths': {'sdk_classification': 'status/old/classification.json'},
            'analysis': {'sdk_detector': detector},
        })
        startup.atomic_json(root / 'status/startup.json', {
            'schema': 1, 'project_root': str(root.resolve()), 'revision': 42,
            'status': status, 'step': 'complete',
            'analysis_labels': {'ida': 'preserved-ida'}, 'steps': {},
            'completion': {'unchanged': True},
        })

    def test_restart_uses_review_gate_and_preserves_inputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.fixture(root)
            ledger_path = root / 'status/translation-ledger.json'
            ledger_path.write_text('{"entries":[{"kept":true}]}', encoding='utf-8')
            config = (root / 'xport-project.json').read_bytes()
            ledger = ledger_path.read_bytes()
            result = startup.refresh_completion(root, 42, False, psyq_label='review-current')
            self.assertEqual((result['revision'], result['status'], result['step']),
                             (43, 'running', 'psyq'))
            self.assertEqual(result['analysis_labels'],
                             {'ida': 'preserved-ida', 'psyq': 'review-current'})
            self.assertEqual((root / 'xport-project.json').read_bytes(), config)
            self.assertEqual(ledger_path.read_bytes(), ledger)

    def test_invalid_requests_do_not_mutate_state(self):
        cases = [
            (41, 'complete', 'new', 'xport', 'REVISION_MISMATCH'),
            (42, 'running', 'new', 'xport', 'NOT_COMPLETE'),
            (42, 'complete', '../bad', 'xport', 'INVALID_PSYQ_LABEL'),
            (42, 'complete', 'new', 'ghidra', 'REQUIRES_XPORT_DETECTOR'),
            (42, 'complete', 'existing', 'xport', 'LABEL_EXISTS'),
        ]
        for revision, status, label, detector, error in cases:
            with self.subTest(error=error), tempfile.TemporaryDirectory() as directory:
                root = Path(directory)
                self.fixture(root, status, detector)
                (root / 'status/psyq-analyzer/runs/existing').mkdir(parents=True)
                before = (root / 'status/startup.json').read_bytes()
                with self.assertRaisesRegex(ValueError, error):
                    startup.refresh_completion(root, revision, False, psyq_label=label)
                self.assertEqual((root / 'status/startup.json').read_bytes(), before)

    def test_plain_refresh_retains_existing_route(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.fixture(root)
            self.assertEqual(startup.refresh_completion(root, 42, False)['step'], 'verify_frontier')

    def test_inventory_excludes_accepted_outputs_but_retains_originals(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.fixture(root)
            config_path = root / 'xport-project.json'
            config = startup.read_json(config_path)
            config['paths']['ida_exports'] = 'orig/reviewed/images'
            startup.atomic_json(config_path, config)
            for relative in ('orig/legacy.bin', 'orig/reviewed/note.bin',
                             'orig/reviewed/images/program/listing.txt',
                             'orig/independent/program/listing.txt'):
                path = root / relative
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(b'original or generated bytes')
            startup.atomic_json(root / 'status/ghidra/accepted-custom.json',
                                {'destination': 'orig/independent/program'})
            result = startup.inventory(root)
            self.assertEqual({row['path'] for row in result['files']},
                             {'orig/legacy.bin', 'orig/reviewed/note.bin'})
            before = result['files'][0]['sha256']
            (root / 'orig/legacy.bin').write_bytes(b'changed original')
            self.assertNotEqual(startup.inventory(root)['files'][0]['sha256'], before)

    def test_inventory_does_not_hide_disc_inputs_or_whole_orig(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            self.fixture(root)
            for relative in ('orig/legacy.bin', 'iso/disc.bin'):
                path = root / relative
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(b'preserved input')
            startup.atomic_json(root / 'status/ghidra/accepted-foreign.json',
                                {'destination': 'iso'})
            startup.atomic_json(root / 'status/ghidra/accepted-root.json',
                                {'destination': 'orig'})
            result = startup.inventory(root)
            self.assertEqual({row['path'] for row in result['files']},
                             {'orig/legacy.bin', 'iso/disc.bin'})


if __name__ == '__main__':
    unittest.main()
